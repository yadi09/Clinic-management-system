#!/usr/bin/env python3
"""Generate the regression catalogue from the tests themselves.

Every regression test carries an ID in its name (Go: TestREG_<DOMAIN>_<NNN>_…,
Vitest/Playwright: "REG-…-NNN …"). This walks the test files and prints a Markdown
catalogue: ID, behaviour (the test's doc comment), layer, file, and any KnownBug
marker. The catalogue is therefore always the code's own truth, never a stale list.

    python3 scripts/test/catalog.py > docs/regression-catalog.md
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
rows = []

go_test = re.compile(r"^func (Test(?:REG_[A-Z]+_\d+\w*|\w*Integration\w*|D\d+\w*|\w+))\(t \*testing\.T\)")
for base, _, files in os.walk(os.path.join(ROOT, "backend")):
    for fn in files:
        if not fn.endswith("_test.go"):
            continue
        path = os.path.join(base, fn)
        rel = os.path.relpath(path, ROOT)
        lines = open(path, encoding="utf-8").read().splitlines()
        for i, line in enumerate(lines):
            m = go_test.match(line)
            if not m or m.group(1) == "TestMain":
                continue
            name = m.group(1)
            # Doc comment: the contiguous // lines above the func.
            doc, j = [], i - 1
            while j >= 0 and lines[j].startswith("//"):
                doc.insert(0, lines[j][2:].strip())
                j -= 1
            text = " ".join(doc)
            text = re.sub(r"^" + re.escape(name) + r":?\s*", "", text)
            # Body until the next top-level func, to find KnownBug markers.
            body = []
            for k in range(i + 1, len(lines)):
                if lines[k].startswith("func "):
                    break
                body.append(lines[k])
            bugs = sorted(set(re.findall(r'KnownBug\(t,\s*"([\w-]+)"', "\n".join(body))))
            rid = name
            mm = re.match(r"TestREG_([A-Z]+)_(\d+)", name)
            if mm:
                rid = f"REG-{mm.group(1)}-{mm.group(2)}"
            layer = "API" if "/tests/regression/" in path else "Integration" if ("Integration" in name or "integration_test" in fn) else "Unit"
            rows.append((rid, layer, text[:260] or name, rel, ", ".join(bugs)))

ts_test = re.compile(r"""\b(?:test|it)(?:\.fails)?\(\s*["'`](REG-[A-Z0-9-]+)\s*([^"'`]*)["'`]""")
for sub in ("frontend/src", "frontend/e2e"):
    for base, _, files in os.walk(os.path.join(ROOT, sub)):
        if "node_modules" in base:
            continue
        for fn in files:
            if not re.search(r"\.(test|spec)\.tsx?$", fn):
                continue
            path = os.path.join(base, fn)
            rel = os.path.relpath(path, ROOT)
            src = open(path, encoding="utf-8").read()
            for m in ts_test.finditer(src):
                known = "test.fails" in src[max(0, m.start() - 12):m.start() + 12] or "KNOWN BUG" in m.group(2)
                bug = re.search(r"KNOWN BUG ([\w-]+)", m.group(2))
                layer = "E2E" if "/e2e/" in path else "Frontend unit"
                rows.append((m.group(1), layer, m.group(2).strip()[:260], rel, bug.group(1) if bug else ("known" if known else "")))

rows.sort(key=lambda r: (r[1] != "API", r[0]))
print("# Regression catalogue\n")
print("Generated by `scripts/test/catalog.py` from the tests themselves; do not edit by hand.\n")
print(f"{len(rows)} tests · {sum(1 for r in rows if r[4])} currently guarding a known bug.\n")
print("| ID | Layer | Behaviour protected | File | Known bug |")
print("|---|---|---|---|---|")
for rid, layer, text, rel, bugs in rows:
    print(f"| {rid} | {layer} | {text.replace('|', '/')} | `{rel}` | {bugs} |")
