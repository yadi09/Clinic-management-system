/** The default wording for a label in a language mode. */
export function defaultLabel(key: string, language: "en" | "am" | "both"): string {
  const l = LABELS[key];
  if (!l) return key;
  if (language === "am") return l.am || l.en;
  if (language === "both") return l.am ? `${l.en} · ${l.am}` : l.en;
  return l.en;
}
